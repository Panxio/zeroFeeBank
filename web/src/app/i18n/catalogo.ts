export function interpolar(plantilla: string, params?: Record<string, string | number>): string {
  if (!params) return plantilla;
  return plantilla.replace(/\{(\w+)\}/g, (match, clave) => {
    return params[clave] !== undefined ? String(params[clave]) : match;
  });
}

